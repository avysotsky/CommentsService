#!/usr/bin/env python3
"""Run an explicit migration/schema check using the built application image."""
import argparse
import os
from pathlib import Path
import subprocess

p = argparse.ArgumentParser(description=__doc__)
p.add_argument('command', choices=['migrate', 'check'])
p.add_argument('--service', choices=['database', 'test-database'], default='database')
p.add_argument('--benchmark', action='store_true', help='Use comments_benchmark in the test-database service.')
p.add_argument('--env-file', default='.env')
p.add_argument('--project', default='commentsservice')
p.add_argument('--compose-file', action='append')
a = p.parse_args()
if a.benchmark: a.service = 'test-database'
# The environment file is generated by init-env.py: literal KEY=value, no shell evaluation.
values = dict(line.split('=', 1) for line in Path(a.env_file).read_text().splitlines()
              if '=' in line and not line.lstrip().startswith('#'))
test = a.service == 'test-database'
key = 'TEST_DB_APP_PASSWORD' if test else 'DB_APP_PASSWORD'
env = os.environ.copy()
env['PGPASSWORD'] = os.environ.get(key) or values[key]
compose = ['docker', 'compose']
for file in a.compose_file or ['compose.yaml']:
    compose += ['-f', file]
compose += ['--env-file', a.env_file, '-p', a.project, '--profile', 'testing']
command = '--migrate' if a.command == 'migrate' else '--check-database'
subprocess.run(compose + ['run', '--rm', '--no-deps', '-e', 'PGHOST=' + a.service,
    '-e', 'PGDATABASE=' + ('comments_benchmark' if a.benchmark else 'comments_test' if test else 'comments'), '-e', 'PGPASSWORD',
    'app', command], env=env, check=True)
