import { createElement } from 'react';
import type { ReactNode } from 'react';
import { safeHomePage } from './model';

export function CommentText({ text, validated = false }: { text: string; validated?: boolean }) {
  if (!validated && !/<\s*[/!?\p{L}]/u.test(text)) return <>{text}</>;
  if (text.length > 65536 || /<!|<\?/.test(text)) return <>{text}</>;
  const document = new DOMParser().parseFromString(`<root>${text}</root>`, 'application/xml');
  if (document.querySelector('parsererror') || document.documentElement.nodeName !== 'root') return <>{text}</>;
  let count = 0;
  function render(node: Node, depth: number, inLink: boolean, key: number): ReactNode {
    if (++count > 4096 || depth > 32) throw new Error('Complex markup');
    if (node.nodeType === Node.TEXT_NODE) return node.textContent;
    if (node.nodeType !== Node.ELEMENT_NODE) throw new Error('Unsupported node');
    const element = node as Element, tag = element.tagName;
    if (element.namespaceURI || !['a', 'i', 'strong', 'code'].includes(tag)) throw new Error('Unsupported tag');
    if (tag === 'a' && inLink) throw new Error('Nested link');
    for (const attribute of element.attributes) {
      // rel is generated by the server, never copied into the rendered element.
      if (tag !== 'a' || attribute.namespaceURI || !['href', 'title', 'rel'].includes(attribute.name)) throw new Error('Unsupported attribute');
    }
    const children = Array.from(element.childNodes, (child, index) => render(child, depth + 1, inLink || tag === 'a', index));
    if (tag !== 'a') return createElement(tag, { key }, children);
    const href = safeHomePage(element.getAttribute('href'));
    if (!href) throw new Error('Unsafe link');
    return <a key={key} href={href} title={element.getAttribute('title') ?? undefined} rel="noopener noreferrer nofollow">{children}</a>;
  }
  try { return <>{Array.from(document.documentElement.childNodes, (node, index) => render(node, 1, false, index))}</>; }
  catch { return <>{text}</>; }
}
